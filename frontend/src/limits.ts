/**
 * 프런트엔드의 모든 크기·개수 상한. 백엔드의 config.py(환경 변수)와 대칭이다.
 *
 * 숫자를 코드 안에 직접 쓰지 마라 (CLAUDE.md 1.5). 여기 상수 하나만 바꾸면
 * 전부 반영돼야 한다. 이미지 데이터가 들어올 때 값이 크게 달라진다.
 *
 * ---
 *
 * **상수마다 `분류:`가 달려 있다. 안 달면 `limits-rules.spec.ts`가 운다.**
 *
 * 묻는 것은 **"무엇이 이 숫자를 붙잡고 있나"** 하나다 (open-decisions.md
 * "상한은 누가 정했느냐로 갈리고, 우리 기기가 정한 것은 끌 수 있다", 2026-08-19).
 *
 * | 분류 | 끄면 무슨 일이 나나 | 끌 수 있나 |
 * |---|---|---|
 * | **우리 기기가 정했다** | 느려지거나 안 끝나거나 탭이 죽는다. **그 판정이 기기마다 다르다** | **끈다** |
 * | **파일이 나간 뒤가 요구한다** | 만들어진 파일이 **밖에서** 안 열리거나 못 나간다 | 못 끈다 |
 * | **계산 자체가 요구한다** | 계산이 성립하지 않는다. 기기와 무관하다 | 못 끈다 |
 * | **교실을 보고 골랐다** | 자원과 무관하다. **꺼도 학생이 얻는 것이 없다** | 못 끈다 |
 * | **알림이다** | 상한을 끈 학생에게 남는 **유일한 신호**가 사라진다 | 못 끈다 |
 * | **상한이 아니다** | 표시 분량·가공 규격·동작 시간·계수. 스위치의 대상이 아니다 | — |
 *
 * **첫 줄이 거의 전부라는 것이 이 분류의 요점이다.** `MLJS_*_ROW_LIMIT`은 구현의
 * 천장처럼 보이지만 근거가 전부 **개발 PC 한 대**(i5-1135G7 · RAM 7.7GB)에서 잰
 * 시간과 메모리다 — 두 배 빠른 기기에서는 그만큼 근거를 잃는다.
 *
 * **`알림이다`에는 `PROJECT_FILE_WARN_BYTES` 하나가 산다** (2026-08-27). 자리를 먼저
 * 세워 둔 덕에 그 상수가 들어올 때 갈 칸이 있었다 — 칸이 없으면 검사가 우는 채로 아무
 * 칸에나 들어간다.
 *
 * **마지막 줄이 있는 이유는 이 파일이 상한만 사는 곳이 아니어서다.** webp 품질과
 * 알림 시간이 여기 함께 산다. 스위치를 "이 파일 전부"로 정의하면 그것들까지 꺼진다.
 *
 * **이름으로 판정하지 마라 — 근거로 판정한다.** `사람이 골랐다`라는 칸이 있었는데
 * 마흔넷이 전부 사람이 골랐으므로 아무것도 안 가렸다 (R6 감사 C-6).
 */

/**
 * 한 단위 올라갈 때의 배수. 상한이 아니라 단위다.
 *
 * **화면이 크기를 올릴 때도 이것을 쓴다** (`useFormat.ts`의 `formatBytes`). 거기서만
 * 1024로 나누면 우리가 `100MB`라 적은 문턱이 화면에서 **`95.4MB`**로 읽혀, 학생이 보는
 * 수가 상한과도 LMS와도 다르다. 실제로 그렇게 갈려 있었다 (R13-4 감사 A-1).
 *
 * 아래 `BYTES_PER_MB`가 이 값의 제곱이라 **둘이 갈라질 수 없다.**
 *
 * **분류: 상한이 아니다.**
 */
export const BYTES_PER_KB = 1_000

/**
 * 바이트를 사람이 읽는 MB로 바꿀 때 쓴다. 상한이 아니라 단위다.
 *
 * **십진 백만이다. `1024 × 1024`로 되돌리지 마라**
 * (open-decisions.md "MB는 십진 백만이다").
 *
 * 이 저장소가 **밖에서 가져온 유일한 크기 기준이 십진**이다 — LMS 첨부 상한
 * 100MB이고, 휴대폰 저장 공간도 클라우드 용량도 같다. 이진으로 두면 우리가 "100MB"라
 * 적은 문턱이 실제로는 104.9MB가 되어, **LMS가 거절할 파일에 경고를 안 띄운다.**
 *
 * 그리고 SI에서 `MB`는 10⁶이라, 십진으로 맞추는 순간 화면의 "MB"가 맞는 말이 된다 —
 * 학생에게 `MiB`를 설명할 일이 없어진다.
 *
 * **엇갈리는 자리 하나는 알고 있다** — 윈도 탐색기는 이진을 "MB"라 부르므로 탐색기가
 * `5MB`라 부르는 파일은 실제 5.24MB다. 근거는 위 결정문에 있다.
 *
 * **분류: 상한이 아니다.**
 */
export const BYTES_PER_MB = BYTES_PER_KB * BYTES_PER_KB

const MB = BYTES_PER_MB

