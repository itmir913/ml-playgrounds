/**
 * 등록부가 "무엇에서 되는가"를 적는 방식 (architecture.md §9).
 *
 * **배열이 아니라 Record인 이유가 이 파일의 전부다.** 축의 값이 하나 늘었을 때
 * `readonly DataType[]`은 아무 말도 하지 않는다 - 부분집합은 언제나 올바른 배열이기
 * 때문이다. 그러면 이미지가 들어온 날 결측치 채우기가 이미지에서 뜨거나 안 뜨는 것은
 * **우연**이 되고, 아무도 그 항목을 다시 보지 않는다.
 *
 * Record는 칸이 비면 컴파일이 깨진다. 길어지는 것은 대가가 아니라 목적이다.
 *
 * **타입 주석이 강제 장치의 나머지 절반이다.** 등록부 배열에 `: readonly Xxx[]`를
 * 붙이지 않으면 TypeScript가 리터럴을 그대로 추론해 축이 늘어도 조용하다.
 * `as const`도 같은 이유로 등록부에 쓰지 마라.
 *
 * **`false`는 "이 조합에서 성립하지 않는다" 하나만 뜻한다** (§9.2.1). "아직 안 만들었다"는
 * `false`가 아니라 **줄이 없는 것**이다 - 등록부에 항목이 있다는 것은 만들어져 있다는
 * 뜻이고, 만들다 만 것은 올리지 않는다. 그래서 'planned' 같은 세 번째 상태도 없다.
 */

/**
 * 축 하나에 대한 선언. **값마다 칸이 있어야 한다.**
 *
 * `Partial<>`로 감싸거나 옵셔널(`?`) 필드로 두지 마라. 그 순간 빠뜨림이 합법이 되고
 * 이 파일이 있는 이유가 사라진다.
 */
export type Axis<Value extends string> = Readonly<Record<Value, boolean>>

/**
 * 이 축 값에서 성립하는가.
 *
 * 등록부 바깥에서는 이 함수만 쓴다 - **장황함은 선언하는 자리에만 두고 부르는 자리로
 * 새게 두지 않는다.** 축을 배열에서 Record로 바꿨는데도 판정 함수들의 모양이 그대로인
 * 것이 이 한 겹의 값어치다.
 */
export function supports<Value extends string>(axis: Axis<Value>, value: Value): boolean {
  return axis[value]
}
