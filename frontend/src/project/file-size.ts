import { PROJECT_FILE_WARN_BYTES } from '@/limits'

/**
 * 제출을 막을 만큼 큰가.
 *
 * **경계는 넘어야 참이다.** 딱 100MB인 파일은 근거가 된 LMS 상한("대략 100MB")에
 * 아직 안 걸리므로 조용히 둔다 — 경고를 한 칸 일찍 띄우는 쪽이 안전해 보이지만,
 * 그러면 아무 문제 없는 파일에 뜨는 경고가 되고 **뜨는 경고를 학생이 무시하기
 * 시작하면 정작 필요할 때 안 읽힌다.**
 */
export function needsSizeWarning(bytes: number): boolean {
  return bytes > PROJECT_FILE_WARN_BYTES
}
